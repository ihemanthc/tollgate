NOTEBOOKS: dict[str, Callable[[], list[Cell]]] = {"kaggle_train.ipynb": kaggle_train}


def ruff_format(source: str) -> str:
    """Code cells in ruff's own style, so `ruff format` never rewrites a generated notebook."""
    done = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", "notebooks/cell.py", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
        cwd=NOTEBOOK_DIR.parent,
    )
    return done.stdout.rstrip("\n")


def build(cells: list[Cell]) -> nbformat.NotebookNode:
    nb = new_notebook(
        cells=[
            new_markdown_cell(source, id=f"cell-{i:02d}")
            if kind == "md"
            else new_code_cell(ruff_format(source), id=f"cell-{i:02d}")
            for i, (kind, source) in enumerate(cells)
        ],
        metadata={
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
            "accelerator": "nvidiaTeslaT4",
        },
    )
    nbformat.validate(nb)
    return nb


def render(name: str) -> str:
    return nbformat.writes(build(NOTEBOOKS[name]())) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a notebook is stale")
    args = parser.parse_args()
    stale = []
    for name in NOTEBOOKS:
        path = NOTEBOOK_DIR / name
        text = render(name)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path}")
    if stale:
        print(f"stale: {stale}; run scripts/make_notebook.py", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
