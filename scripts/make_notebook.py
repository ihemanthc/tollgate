"""Generate notebooks/*.ipynb. Notebooks are never edited by hand (CLAUDE.md): edit this file.

    uv run python scripts/make_notebook.py           # (re)write every notebook
    uv run python scripts/make_notebook.py --check   # exit 1 if a committed notebook is stale

Cells are plain Python (no `!` or `%` magics) so tests can compile every one of them.
No --limit: this writes notebooks and processes no rows; the notebook's own settings cell
carries the row limits.
"""

